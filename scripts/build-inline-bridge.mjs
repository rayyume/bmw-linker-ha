import { readFileSync, writeFileSync } from "node:fs";

const sourcePath = new URL("../bmw-linker-ha-bridge.js", import.meta.url);
const outputPath = new URL("../bmw-linker-ha-inline.js", import.meta.url);
const packagePath = new URL("../bmw-linker-ha-bridge.scriptable", import.meta.url);
const installerPath = new URL("./install-bridge.js", import.meta.url);
const installerPackagePath = new URL("../bmw-linker-ha-setup.scriptable", import.meta.url);
const senderSignature = "module.exports.pushVehicleState = async (snapshot) => {";
const source = readFileSync(sourcePath, "utf8");
if (!source.includes(senderSignature)) {
  throw new Error("Expected one pushVehicleState module export");
}

const bridge = source
  .slice(source.indexOf(senderSignature))
  .trimEnd()
  .replace(senderSignature, "const pushVehicleState = async (snapshot, webhookUrl) => {")
  .replaceAll("HA_WEBHOOK_URL", "webhookUrl")
  .split("\n")
  .map((line) => (line ? "  " + line : ""))
  .join("\n");

const inline = [
  "// Generated by scripts/build-inline-bridge.mjs.",
  "// Paste above: await new Widget(Script.name(), {",
  "{",
  bridge,
  `
  const webhookKey = "bmw-linker-ha.webhook-url." + Script.name();
  const menuName = "bmwLinkerHaWebhook";
  const readWebhook = () => Keychain.contains(webhookKey) ? Keychain.get(webhookKey) : "";
  const webhookStatus = () => readWebhook() ? "已设置" : "未设置";

  Widget = class extends Widget {
    async getAppViewOptions() {
      const options = await super.getAppViewOptions();
      return {
        ...options,
        settingItems: [
          {
            name: menuName,
            label: "Home Assistant Webhook",
            type: "cell",
            icon: { name: "house.fill", color: "#1699cb" },
            needLoading: true,
            desc: webhookStatus(),
          },
          ...options.settingItems,
        ],
        onItemClick: async (item, ...args) => {
          if (item.name !== menuName) return options.onItemClick(item, ...args);

          const alert = new Alert();
          alert.title = "Home Assistant Webhook";
          alert.message = "粘贴 HA 集成生成的完整 Webhook URL。清空后保存可停用推送。";
          alert.addSecureTextField("Webhook URL", readWebhook());
          alert.addAction("保存");
          alert.addCancelAction("取消");
          if (await alert.presentAlert() === 0) {
            const url = alert.textFieldValue(0).trim();
            if (!url) {
              if (Keychain.contains(webhookKey)) Keychain.remove(webhookKey);
            } else if (isHaWebhookUrl(url)) {
              Keychain.set(webhookKey, url);
            } else {
              await this.generateAlert("地址有误", "请粘贴 HA 集成显示的完整 Webhook URL。", ["确定"]);
            }
          }
          return { desc: { value: webhookStatus() } };
        },
      };
    }

    async getData(forceRefresh = false) {
      const data = await super.getData(forceRefresh);
      if (!forceRefresh && data?.properties && !data.black) {
        const url = readWebhook();
        if (url) await pushVehicleState(data.properties, url);
      }
      return data;
    }
  };
}
`,
].join("\n");
writeFileSync(outputPath, inline);

const scriptablePackage = JSON.parse(readFileSync(packagePath, "utf8"));
scriptablePackage.script = source;
writeFileSync(packagePath, JSON.stringify(scriptablePackage, null, 2) + "\n");

const installer = readFileSync(installerPath, "utf8");
const installerPackage = {
  always_run_in_app: true,
  icon: { color: "blue", glyph: "mobile-alt" },
  name: "bmw-linker-ha-setup",
  script: installer.replace("/* generated bridge */ null", () => JSON.stringify(inline)),
  share_sheet_inputs: [],
};
writeFileSync(installerPackagePath, JSON.stringify(installerPackage, null, 2) + "\n");
