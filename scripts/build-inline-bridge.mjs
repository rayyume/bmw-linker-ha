import { readFileSync, writeFileSync } from "node:fs";

const sourcePath = new URL("../bmw-linker-ha-bridge.js", import.meta.url);
const outputPath = new URL("../bmw-linker-ha-inline.js", import.meta.url);
const exportAssignment = "module.exports.pushVehicleState =";
const source = readFileSync(sourcePath, "utf8").trimEnd();
if (source.split(exportAssignment).length !== 2) {
  throw new Error("Expected one pushVehicleState module export");
}

const bridge = source
  .split("\n")
  .slice(1)
  .map((line) => (line ? "  " + line.replace(exportAssignment, "const pushVehicleState =") : ""))
  .join("\n");

writeFileSync(outputPath, [
  "// Generated by scripts/build-inline-bridge.mjs.",
  "// Paste below: let data = await this.getData();",
  "if (data?.properties && !data.black) {",
  bridge,
  "",
  "  await pushVehicleState(data.properties);",
  "}",
  "",
].join("\n"));
